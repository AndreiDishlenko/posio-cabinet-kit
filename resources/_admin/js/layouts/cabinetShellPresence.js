import { reactive } from 'vue';

// Боковое меню и плавающие виджеты угла смонтированы вне дерева страницы, поэтому
// о том, нужны ли они сейчас на экране, сообщает сам каркас страницы.
//
// Счётчик, а не флаг: на переходе старый каркас снимается, а новый заявляет о
// себе в одном и том же кадре, и при флаге исход зависел бы от их порядка —
// слой мог бы погаснуть и подняться заново, потеряв прокрутку панели и начатый
// разговор с помощником.
export const cabinetShellPresence = reactive({
	pages: 0,
	menu_disabled: false,

	// Обучение занимает внимание целиком, поэтому напоминание о первых шагах при
	// нём молчит. Признак общий: список смонтирован вне страницы и о ходе
	// обучения иначе не узнает.
	tour_active: false,

	attach(menu_disabled = false) {
		this.pages++;
		this.menu_disabled = menu_disabled;
	},

	detach() {
		this.pages = Math.max(0, this.pages - 1);
	},
});
